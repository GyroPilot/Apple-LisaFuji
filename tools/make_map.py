"""make_map.py: the LisaFuji world map.  Natural Earth 1:110m land (public domain) rasterized to
512 x 137 Lisa pixels, latitude 80 N to 60 S (the station never goes past 51.6), equirectangular.
Lisa pixels are about 1.45 times taller than wide, so 512 x 137 keeps the land the right shape.
Writes LFJ-MAP.TEXT: unit LfjMap, its own segment, the map as run-length strings (one per row,
runs alternate sea, land, sea ...), and MapDraw, which paints the land gray with QuickDraw.
Also writes map_preview.png (as the Lisa would show it)."""
import json, sys
from PIL import Image, ImageDraw

MW, MH = 512, 137
N, S = 80.0, -60.0
SS = 4
OUT = sys.argv[1] if len(sys.argv) > 1 else "LFJ-MAP.TEXT"

g = json.load(open("ne_110m_land.geojson", encoding="utf-8"))
big = Image.new("L", (MW * SS, MH * SS), 0)
d = ImageDraw.Draw(big)


def px(lon, lat):
    return ((lon + 180.0) / 360.0 * MW * SS, (N - lat) / (N - S) * MH * SS)


for f in g["features"]:
    geom = f["geometry"]
    polys = geom["coordinates"] if geom["type"] == "MultiPolygon" else [geom["coordinates"]]
    for poly in polys:
        d.polygon([px(lo, la) for lo, la in poly[0]], fill=255)
        for hole in poly[1:]:
            d.polygon([px(lo, la) for lo, la in hole], fill=0)
small = big.resize((MW, MH), Image.BOX).point(lambda v: 255 if v >= 110 else 0)
land = small.load()

# the alphabet: printable ASCII without ' ( ) * { }  (quotes, comments and the pre-flight's brace count)
EXCL = {39, 40, 41, 42, 123, 125}
ALPHA = [chr(c) for c in range(33, 127) if c not in EXCL]
BASE = len(ALPHA)                     # 88


def enc(n):
    out = []
    while n > BASE - 1:
        out += [ALPHA[BASE - 1], ALPHA[0]]      # a full run, then an empty run of the other kind
        n -= BASE - 1
    out.append(ALPHA[n])
    return out


rows = []
for y in range(MH):
    runs, cur, n = [], False, 0          # starts with sea
    for x in range(MW):
        v = land[x, y] > 0
        if v == cur:
            n += 1
        else:
            runs.append(n)
            cur, n = v, 1
    runs.append(n)
    s = []
    for r in runs[:-1] if not cur else runs:     # a trailing sea run need not be written
        s += enc(r)
    rows.append("".join(s))

# decode check, the way the Pascal does it
def val(c):
    k = ord(c) - 33
    if ord(c) > 42: k -= 4
    if ord(c) > 123: k -= 1
    if ord(c) > 125: k -= 1
    return k

chk = Image.new("1", (MW, MH), 1)
cp = chk.load()
for y, s in enumerate(rows):
    x, isl = 0, False
    for c in s:
        v = val(c)
        if isl:
            for i in range(v):
                cp[x + i, y] = 0
        x += v
        isl = not isl
    assert x <= MW, (y, x)
for y in range(MH):
    for x in range(MW):
        assert (cp[x, y] == 0) == (land[x, y] > 0), (x, y)

total = sum(len(r) for r in rows)
pv = Image.new("L", (MW, MH), 255)
pp = pv.load()
for y in range(MH):
    for x in range(MW):
        if land[x, y] and (x + y) % 2 == 0:
            pp[x, y] = 0
pv.resize((MW, int(MH * 1.45)), Image.NEAREST).save("map_preview.png")


def lit(s):
    parts = [s[i:i + 70] for i in range(0, len(s), 70)] or [""]
    q = ["'" + p + "'" for p in parts]
    e = q[-1]
    for p in reversed(q[:-1]):
        e = "concat(%s, %s)" % (p, e)
    return e


L = []
L.append("unit LfjMap;")
L.append("")
L.append("{ REV K  17-Oct-2026  LisaFuji 0.6 REV K: the world map for the space   }")
L.append("{                      station page.  Generated by make_map.py from    }")
L.append("{                      Natural Earth 1:110m land (public domain).      }")
L.append("{                      Do not edit the rows by hand.                    }")
L.append("")
L.append("{ LFJ-MAP.TEXT -- %d x %d Lisa pixels, latitude 80 N (row 0) to 60 S,   }" % (MW, MH))
L.append("{ longitude 180 W (column 0) to 180 E.  Each row is a string of runs,  }")
L.append("{ sea, land, sea ...; a character is a run length (MapVal).  MapDraw   }")
L.append("{ paints the land in a 50 percent gray made here, so it does not need  }")
L.append("{ QuickDraw's own pattern globals.  %5d characters of map in all.    }" % total)
L.append("")
L.append("INTERFACE")
L.append("")
L.append("uses (*$U UnitStd.obj *)   UnitStd,")
L.append("     (*$U UnitHz.obj *)    UnitHz,")
L.append("     (*$U Storage.obj *)   Storage,")
L.append("     (*$U QuickDraw.obj *) QuickDraw;")
L.append("")
L.append("const")
L.append("   mapW = %d;               { map width, Lisa pixels }" % MW)
L.append("   mapH = %d;               { map height }" % MH)
L.append("   mapN = %d;                { latitude of row 0 }" % int(N))
L.append("   mapS = %d;               { latitude below the last row }" % int(S))
L.append("")
L.append("procedure MapDraw (left, top : integer);")
L.append("")
L.append("")
L.append("IMPLEMENTATION")
L.append("")
L.append("{ The map is data in code: its own segment, LFJMap. }")
L.append("{$S LFJMap}")
L.append("")
L.append("procedure MapRow (y : integer; var s : Str255);")
L.append("{ Row y of the map as runs. }")
L.append("begin")
L.append("   case y of")
for y, s in enumerate(rows):
    L.append("      %d : s := %s;" % (y, lit(s)))
L.append("      otherwise")
L.append("         s := ''")
L.append("   end")
L.append("end;")
L.append("")
L.append("function MapVal (c : char) : integer;")
L.append("{ One run length: printable ASCII from ! upward, skipping the quote, the }")
L.append("{ parentheses, the star and the braces.                                  }")
L.append("var k : integer;")
L.append("begin")
L.append("   k := ord(c) - 33;")
L.append("   if ord(c) > 42 then k := k - 4;")
L.append("   if ord(c) > 123 then k := k - 1;")
L.append("   if ord(c) > 125 then k := k - 1;")
L.append("   MapVal := k")
L.append("end;")
L.append("")
L.append("procedure MapDraw {left, top : integer};")
L.append("{ Paint the land gray with its top-left corner at (left, top), then a  }")
L.append("{ frame.  The window must be the current port.                          }")
L.append("var y, x, i, v : integer;")
L.append("    s          : Str255;")
L.append("    onLand     : boolean;")
L.append("    pat        : Pattern;")
L.append("    r          : Rect;")
L.append("begin")
L.append("   for i := 0 to 7 do")
L.append("      if odd(i) then")
L.append("         pat[i] := 85")
L.append("      else")
L.append("         pat[i] := 170;")
L.append("   PenNormal;")
L.append("   PenPat(pat);")
L.append("   for y := 0 to mapH - 1 do begin")
L.append("      MapRow(y, s);")
L.append("      x := 0;")
L.append("      onLand := false;")
L.append("      for i := 1 to length(s) do begin")
L.append("         v := MapVal(s[i]);")
L.append("         if onLand and (v > 0) then begin")
L.append("            MoveTo(left + x, top + y);")
L.append("            LineTo(left + x + v - 1, top + y)")
L.append("         end;")
L.append("         x := x + v;")
L.append("         onLand := not onLand")
L.append("      end")
L.append("   end;")
L.append("   PenNormal;")
L.append("   SetRect(r, left - 1, top - 1, left + mapW + 1, top + mapH + 1);")
L.append("   FrameRect(r)")
L.append("end;")
L.append("")
L.append("end.")
open(OUT, "w", newline="\n").write("\n".join(L) + "\n")
print("rows", MH, "chars", total, "longest row", max(len(r) for r in rows), "lines", len(L))
